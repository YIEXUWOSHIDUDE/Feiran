"""The synthetic sample a guest workspace starts with: a CV profile, its lines, one example job
and a CV for that job, from examples/guest_sample.json. No real person, school, employer or
posting is in it, and nothing in it was generated by a model.

It is put in through the store's own entry points (import_facts, save_profile, create_job,
save_requirements, create_draft, set_note), so it is checked by the same rules as anything a
user saves, and the guest then works on it through the same app, AI included within its
allowance. The job's requirements are found by the heading rules (requirement_flow, no model)
and the CV is the saved profile as written (cv.build_draft_from_facts), the first stage of a
normal preparation; the stages a model would do next are recorded as not run yet, and how to run
them. The page says all of this.
"""

import json
from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path
from typing import Any

from feiran.cv_status import stage_entry
from feiran.requirement_flow import propose_requirements
from feiran.tenant_store import GUEST_OLD_STAGES, UserWorkspace
from feiran.v2_flow import auto_decide

SAMPLE = Path(__file__).resolve().parent.parent / "examples" / "guest_sample.json"
LANGUAGE = "en"
REQUEST = "guest-sample"
# How the sample CV was made, in the words the page shows beside it (web/zh.js translates them).
# Not "Not reworded: ...", which reads as a failure: the sample was made without a model on
# purpose. The same words replace what samples made before guests could use AI said.
NO_AI_REWORDING = ("AI rewording not run yet: the sample CV was prepared without AI. Choose Reword with DeepSeek to "
                   "try it; it uses this guest workspace's AI allowance.")
NO_AI_LAYOUT = ("AI adjustment for this job not run yet: the sample CV was prepared without AI. Choose Adjust for "
                "this job to try it (it uses this guest workspace's AI allowance), or Fit to one page.")
assert {NO_AI_REWORDING, NO_AI_LAYOUT} == set(GUEST_OLD_STAGES.values())


@lru_cache(maxsize=1)
def sample() -> dict[str, Any]:
    """The checked-in sample, read once per process."""
    return json.loads(SAMPLE.read_text(encoding="utf-8"))


def seed(user: UserWorkspace, *, now: datetime | None = None) -> str:
    """Put the sample into a new, empty guest workspace; returns the example job's ID. Each step
    is one of the store's own transactions; a failure raises, and the caller removes the half-made
    workspace (it is never given a session)."""
    data = sample()
    captured = (now or datetime.now(timezone.utc)).isoformat()
    facts = user.import_facts(data["facts"])
    profile = user.save_profile(LANGUAGE, data["profile"], expected_version=0)
    posting = data["job"]
    jd = {"text": posting["text"], "title": posting["title"], "company": posting["company"],
          "location": posting["location"], "source": posting["source"], "captured_at": captured}
    job_id = user.create_job(jd, request_id=REQUEST)["job_id"]
    # The heading rules alone (no chat given): the requirement lines under the posting's own headings.
    candidates = propose_requirements({"jd": user.get_job(job_id)["jd"], "facts": [], "selected_requirements": []})
    user.save_requirements(job_id, candidates, auto_decide(candidates), expected_version=0)
    # Built for the requirements just decided, as a preparation's first stage is, so that
    # rewording and adjusting it (with AI, within the guest's allowance) can build on it.
    draft = user.create_draft(job_id, LANGUAGE, request_id=REQUEST, expected_profile_version=profile["version"],
                              expected_facts=[(fact["id"], fact["version"]) for fact in facts], for_requirements=True)
    user.set_note(job_id, "cv-language", {"language": LANGUAGE})
    user.set_note(job_id, f"cv-status-{LANGUAGE}", {
        "draft_material_id": draft["material_id"], "updated_at": captured,
        "stages": [stage_entry("draft", "done", "Built from your saved material."),
                   stage_entry("rewording", "skipped", NO_AI_REWORDING, "guest_no_ai"),
                   stage_entry("layout", "skipped", NO_AI_LAYOUT, "guest_no_ai")]})
    return job_id
